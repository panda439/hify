-- 007-document-processing-notice：文档处理的「成功但有提示」通道。
--
-- 在这一列之前，系统只能表达两种处理结局：成功、失败。而第三种真实存在——
-- 处理完成了、文档可用、但有一部分内容没能进去。documents 只有 error_message
-- 一个字段承载"要对用户说的话"，它的语义与 status = 'failed' 绑死，
-- MarkDocumentReady 更是硬编码 error_message = NULL：**一份成功入库的文档，
-- 在数据模型上没有任何位置可以挂一条提示**。
--
-- 直接后果是一份 50 页合同后 5 页是扫描签字页时，前 45 页正常入库、状态显示
-- 「就绪」，而用户完全不知道那 5 页没进去。他问附件条款，检索什么都召不回来。
-- 一个明说的失败让人知道下一步做什么；一个静默的缺失让人对整个系统失去校准。
--
-- 格式：未能提取文本的页码，1-indexed、升序、去重、逗号分隔、无空格（"2,4"）。
-- NULL 表示"没有缺页"**或**"不知道"（见下），两者不区分。
--
-- ⚠️ 不加 CHECK 约束：这一列的内容是一个**列表**，"逗号分隔的升序正整数"不是
-- MySQL 的 CHECK 能便宜表达的结构，硬写正则既脆弱又难读。不变量改由
-- internal/knowledge/notice.go 的纯函数在编码时保证，并由 notice_test.go 锁定。
-- 这不是"约束更弱"，是这一列的不变量本来就不属于数据库能便宜表达的那一类。
--
-- ⚠️ 不建索引：从不按它查询、排序或过滤，它只被整行读出来展示。
--
-- ⚠️ **不做任何回填**：系统并不知道一份从未重新处理过的存量文档当初有没有缺页
-- ——那个信息在当时的抽取阶段就没被记录。凭空标"有缺页"是编造，标"没缺页"
-- 同样是编造。NULL 是唯一诚实的值，且它天然渲染为"无提示"，与改动前的呈现
-- 完全一致。用户对某份文档存疑时，重新处理它就能拿到准确的提示。
ALTER TABLE documents ADD COLUMN unextracted_pages TEXT NULL;
