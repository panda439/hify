-- 008-unparseable-page-notice：解析失败的页面也要能被用户看见。
--
-- 007 加了 unextracted_pages（没有文本层的页），但那**只覆盖了两种缺失里的一种**。
-- 页面进不了知识库有两条路：
--   * 没有文本层（扫描图）        → unextracted_pages
--   * 根本解析不了、被整页跳过     → 本列
-- 后者来自 006 给 rsc.io/pdf 加的逐页 recover：那个库遇到损坏或不受支持的页面
-- 结构会 panic，兜住之后这一页被跳过——于是它**在统计有没有文本层之前就已经消失
-- 了**，textLayerCoverage 看到的每一页都有文本，缺页列表为空。实测一篇 15 页的
-- arXiv 论文第 1 页解析失败，用户看到一份「就绪、无提示」的文档而第 1 页不在里面。
--
-- ⚠️ **为什么是第二列而不是并进 unextracted_pages**：两者唯一的共同点是「这页
-- 没进去」，而用户拿它做的事完全不同——无文本层要做 OCR，解析失败**做 OCR 没用**
-- （那页是损坏或不受支持的结构，得换工具重新导出）。一条消息服务不了两种下一步；
-- 合并存储就必须记「哪些页是哪种原因」，那是第二个维度，也就是 007 的 FR-011
-- 明确禁掉的那个通用 code 字段。
--
-- ⭐ **增生的判据**（这条比这一列本身重要，见 specs/008 的 research.md R1）：
-- 两列不构成「每种原因一列」的许可。第三种原因出现时按这条走——
--   * 它给用户的下一步动作与某个已有列**相同** → 并进那一列；
--   * **不同** → 才有资格开自己的列，且必须先写规格。
-- 列数到 3 是**重新考虑形态**的信号，不是继续加列的许可；但在到达 3 之前不要
-- 提前抽象，两列的重复远比一个为想象中的第 N 种原因设计出来的结构便宜。
--
-- 格式与 unextracted_pages 完全相同（1-indexed、升序、去重、逗号分隔），
-- 两列共用同一套编解码（internal/knowledge/notice.go），不各写一份。
-- 两列**互不重叠**——解析失败的页进不了 textLayerCoverage 的视野，物理上不可能
-- 同时出现；这一点由断言看守，不写去重代码。
--
-- ⚠️ 不回填（同 007）：系统不知道存量文档当初有没有解析失败的页，NULL 是唯一
-- 诚实的值，它同时表示「没有」和「不知道」。
ALTER TABLE documents ADD COLUMN unparseable_pages TEXT NULL;
