-- 010：记录一个 item 的人物身份**没有经过归一**就发布了。
--
-- ⭐ 这一列存在的全部理由是：归一失败现在不再让整个 item 失败，而是退回
-- "每个称呼各自独立成人物"并照常发布关系。那是个**保守但有代价**的降级——
-- 同一个人的几个称呼会变成几个人物，覆盖率看着没变，召回率却会掉，
-- 而关系本身每一条都有真实原文支持，逐条核对都对。
--
-- ⚠️ 所以它必须落在**数据里**，不能只写日志：报告要能回答"这本书有多少块
-- 的人物是没归一过的"，而日志会滚掉、也无法参与 SQL 统计。
-- 只写日志的降级等于静默降级——用户和报告都看不见，指标却已经变了。
ALTER TABLE relation_extraction_items
    ADD COLUMN alias_degraded TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '归一失败后退回独立身份发布：1=这一块的人物未经归一';
